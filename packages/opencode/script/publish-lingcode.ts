#!/usr/bin/env bun
import { $ } from "bun"
import pkg from "../package.json"
import { Script } from "@opencode-ai/script"
import { fileURLToPath } from "url"

const dir = fileURLToPath(new URL("..", import.meta.url))
process.chdir(dir)

const GITHUB_REPO = "lingke-net/lingcode"
const NPM_PACKAGE = "lingcode"
const DOCKER_IMAGE = "ghcr.io/lingke-net/lingcode"
const BIN_NAME = "lingcode"

async function published(name: string, version: string) {
  return (await $`npm view ${name}@${version} version`.nothrow()).exitCode === 0
}

async function publish(dir: string, name: string, version: string) {
  if (process.platform !== "win32") await $`chmod -R 755 .`.cwd(dir)
  if (await published(name, version)) {
    console.log(`already published ${name}@${version}`)
    return
  }
  await $`bun pm pack`.cwd(dir)
  await $`npm publish *.tgz --access public --tag ${Script.channel}`.cwd(dir)
}

const binaries: Record<string, string> = {}
for (const filepath of new Bun.Glob("*/package.json").scanSync({ cwd: "./dist" })) {
  const pkg = await Bun.file(`./dist/${filepath}`).json()
  binaries[pkg.name] = pkg.version
}
console.log("binaries", binaries)
const version = Object.values(binaries)[0]

await $`mkdir -p ./dist/${pkg.name}`
await $`cp -r ./bin ./dist/${pkg.name}/bin`
await $`cp ./script/postinstall.mjs ./dist/${pkg.name}/postinstall.mjs`
await Bun.file(`./dist/${pkg.name}/LICENSE`).write(await Bun.file("../../LICENSE").text())

await Bun.file(`./dist/${pkg.name}/package.json`).write(
  JSON.stringify(
    {
      name: NPM_PACKAGE,
      bin: {
        [pkg.name]: `./bin/${pkg.name}`,
      },
      scripts: {
        postinstall: "bun ./postinstall.mjs || node ./postinstall.mjs",
      },
      version: version,
      license: pkg.license,
      optionalDependencies: binaries,
    },
    null,
    2,
  ),
)

const tasks = Object.entries(binaries).map(async ([name]) => {
  await publish(`./dist/${name}`, name, binaries[name])
})
await Promise.all(tasks)
await publish(`./dist/${pkg.name}`, NPM_PACKAGE, version)

const platforms = "linux/amd64,linux/arm64"
const tags = [`${DOCKER_IMAGE}:${version}`, `${DOCKER_IMAGE}:${Script.channel}`]
const tagFlags = tags.flatMap((t) => ["-t", t])

if (!Script.preview) {
  await $`docker buildx build --platform ${platforms} ${tagFlags} --push .`

  const arm64Sha = await $`sha256sum ./dist/lingcode-linux-arm64.tar.gz | cut -d' ' -f1`.text().then((x) => x.trim())
  const x64Sha = await $`sha256sum ./dist/lingcode-linux-x64.tar.gz | cut -d' ' -f1`.text().then((x) => x.trim())
  const macX64Sha = await $`sha256sum ./dist/lingcode-darwin-x64.zip | cut -d' ' -f1`.text().then((x) => x.trim())
  const macArm64Sha = await $`sha256sum ./dist/lingcode-darwin-arm64.zip | cut -d' ' -f1`.text().then((x) => x.trim())

  const [pkgver, _subver = ""] = Script.version.split(/(-.*)/, 2)

  // AUR package
  const binaryPkgbuild = [
    "# Maintainer: lingke",
    "",
    `pkgname='lingcode-bin'`,
    `pkgver=${pkgver}`,
    `_subver=${_subver}`,
    "options=('!debug' '!strip')",
    "pkgrel=1",
    `pkgdesc='The AI coding agent built for the terminal (Lingke Fork)'`,
    `url='https://github.com/${GITHUB_REPO}'`,
    "arch=('aarch64' 'x86_64')",
    "license=('MIT')",
    `provides=('lingcode')`,
    `conflicts=('lingcode')`,
    "depends=('ripgrep')",
    "",
    `source_aarch64=("\${pkgname}_\${pkgver}_aarch64.tar.gz::https://github.com/${GITHUB_REPO}/releases/download/v\${pkgver}\${_subver}/lingcode-linux-arm64.tar.gz")`,
    `sha256sums_aarch64=('${arm64Sha}')`,
    "",
    `source_x86_64=("\${pkgname}_\${pkgver}_x86_64.tar.gz::https://github.com/${GITHUB_REPO}/releases/download/v\${pkgver}\${_subver}/lingcode-linux-x64.tar.gz")`,
    `sha256sums_x86_64=('${x64Sha}')`,
    "",
    "package() {",
    `  install -Dm755 ./lingcode "${pkgdir}/usr/bin/lingcode"`,
    "}",
    "",
  ].join("\n")

  for (const [pkgbuildName, pkgbuildContent] of [["lingcode-bin", binaryPkgbuild]]) {
    for (let i = 0; i < 30; i++) {
      try {
        await $`rm -rf ./dist/aur-${pkgbuildName}`
        await $`git clone ssh://aur@aur.archlinux.org/${pkgbuildName}.git ./dist/aur-${pkgbuildName}`
        await $`cd ./dist/aur-${pkgbuildName} && git checkout master`
        await Bun.file(`./dist/aur-${pkgbuildName}/PKGBUILD`).write(pkgbuildContent)
        await $`cd ./dist/aur-${pkgbuildName} && makepkg --printsrcinfo > .SRCINFO`
        await $`cd ./dist/aur-${pkgbuildName} && git add PKGBUILD .SRCINFO`
        if ((await $`cd ./dist/aur-${pkgbuildName} && git diff --cached --quiet`.nothrow()).exitCode === 0) break
        await $`cd ./dist/aur-${pkgbuildName} && git commit -m "Update to v${Script.version}"`
        await $`cd ./dist/aur-${pkgbuildName} && git push`
        break
      } catch {
        continue
      }
    }
  }

  // Homebrew formula
  const homebrewFormula = [
    "# typed: false",
    "# frozen_string_literal: true",
    "",
    "# This file was generated by GoReleaser. DO NOT EDIT.",
    "class Lingcode < Formula",
    `  desc "The AI coding agent built for the terminal (Lingke Fork)"`,
    `  homepage "https://github.com/${GITHUB_REPO}"`,
    `  version "${Script.version.split("-")[0]}"`,
    "",
    `  depends_on "ripgrep"`,
    "",
    "  on_macos do",
    "    if Hardware::CPU.intel?",
    `      url "https://github.com/${GITHUB_REPO}/releases/download/v${Script.version}/lingcode-darwin-x64.zip"`,
    `      sha256 "${macX64Sha}"`,
    "",
    "      def install",
    `        bin.install "${BIN_NAME}"`,
    "      end",
    "    end",
    "    if Hardware::CPU.arm?",
    `      url "https://github.com/${GITHUB_REPO}/releases/download/v${Script.version}/lingcode-darwin-arm64.zip"`,
    `      sha256 "${macArm64Sha}"`,
    "",
    "      def install",
    `        bin.install "${BIN_NAME}"`,
    "      end",
    "    end",
    "  end",
    "",
    "  on_linux do",
    "    if Hardware::CPU.intel? and Hardware::CPU.is_64_bit?",
    `      url "https://github.com/${GITHUB_REPO}/releases/download/v${Script.version}/lingcode-linux-x64.tar.gz"`,
    `      sha256 "${x64Sha}"`,
    "      def install",
    `        bin.install "${BIN_NAME}"`,
    "      end",
    "    end",
    "    if Hardware::CPU.arm? and Hardware::CPU.is_64_bit?",
    `      url "https://github.com/${GITHUB_REPO}/releases/download/v${Script.version}/lingcode-linux-arm64.tar.gz"`,
    `      sha256 "${arm64Sha}"`,
    "      def install",
    `        bin.install "${BIN_NAME}"`,
    "      end",
    "    end",
    "  end",
    "end",
    "",
    "",
  ].join("\n")

  const token = process.env.GITHUB_TOKEN
  if (!token) {
    console.error("GITHUB_TOKEN is required to update homebrew tap")
  } else {
    const tap = `https://x-access-token:${token}@github.com/lingke-net/homebrew-tap.git`
    await $`rm -rf ./dist/homebrew-tap`
    await $`git clone ${tap} ./dist/homebrew-tap`
    await Bun.file("./dist/homebrew-tap/lingcode.rb").write(homebrewFormula)
    await $`cd ./dist/homebrew-tap && git add lingcode.rb`
    if ((await $`cd ./dist/homebrew-tap && git diff --cached --quiet`.nothrow()).exitCode !== 0) {
      await $`cd ./dist/homebrew-tap && git commit -m "Update to v${Script.version}"`
      await $`cd ./dist/homebrew-tap && git push`
    }
  }
}
